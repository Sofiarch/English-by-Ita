const DICTS = { ar, en };

// Gemini returns Arabic part-of-speech labels; map them to keys + ink colours.
export const POS = {
  "اسم": { key: "noun", ink: "var(--blue)" },
  "فعل": { key: "verb", ink: "var(--pink)" },
  "صفة": { key: "adjective", ink: "var(--yellow)" },
  "ظرف": { key: "adverb", ink: "var(--teal)" },
  "عبارة": { key: "phrase", ink: "var(--violet)" },
  "حرف جر": { key: "preposition", ink: "var(--muted)" },
  "أخرى": { key: "other", ink: "var(--muted)" },
};
export const posInfo = (label) => POS[label] || { key: "other", ink: "var(--muted)" };

/** An error with a translatable code. */
export class AppError extends Error {
  constructor(code, message) {
    super(message || code);
    this.code = code;
  }
}

const I18nContext = createContext(null);

function readLang() {
  try {
    return localStorage.getItem(KEY) === "en" ? "en" : "ar";
  } catch {
    return "ar";
  }
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(readLang);

  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang;
    root.dir = lang === "ar" ? "rtl" : "ltr";
    try { localStorage.setItem(KEY, lang); } catch { /* per-visit only */ }
  }, [lang]);

  const t = useCallback(
    (key, vars) => {
      let s = DICTS[lang][key] ?? DICTS.ar[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
      return s;
    },
    [lang],
  );

  /** Turns any thrown error into a message in the current language. */
  const errorText = useCallback(
    (err) => {
      if (!err) return "";
      if (typeof err === "string") return err;
      if (err.code && DICTS[lang][`err.${err.code}`]) return t(`err.${err.code}`);
      return err.message || t("err.server_error");
    },
    [lang, t],
  );

  const value = useMemo(
    () => ({ lang, dir: lang === "ar" ? "rtl" : "ltr", setLang, toggle: () => setLang((l) => (l === "ar" ? "en" : "ar")), t, errorText }),
    [lang, t, errorText],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
